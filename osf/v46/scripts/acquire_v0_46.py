def window_guard(state_path=None, now=None):
    """Section 3.8: the window's dates are recorded in the budget state file before the first call
    ({"window": {"start_utc": ISO}}); no request before the start, none after start + 72 h. -> hard end."""
    p = Path(STATE_PATH if state_path is None else state_path)
    st = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
    w = (st.get("window") or {}).get("start_utc")
    if not w:
        raise Refused(f"no collection window recorded in {p} (section 3.8)")
    start = datetime.fromisoformat(w)
    end = start + timedelta(hours=WINDOW_HOURS)
    now = now or datetime.now(timezone.utc)
    if now < start:
        raise Refused(f"the window opens at {start.isoformat()} (now {now.isoformat()})")
    if now > end:
        raise Refused(f"the window closed at {end.isoformat()}")
    return end


