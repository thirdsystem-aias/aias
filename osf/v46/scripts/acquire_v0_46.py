def done_ids(raw_path=None):
    """= v0.45 done_ids: call_ids with an answered line (resume skips them)."""
    done = set()
    raw_path = Path(RAW_PATH if raw_path is None else raw_path)
    if raw_path.exists():
        for line in raw_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            if (r.get("text") or "").strip() and not r.get("error") and r.get("status", "ok") == "ok":
                done.add(r["call_id"])
    return done


def _raw_lines(raw_path):
    raw_path = Path(raw_path)
    if not raw_path.exists():
        return []
    out = []
    for line in raw_path.read_text(encoding="utf-8").splitlines():
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def block_cost(raw_path, block):
    """Actual cost of every raw line of one block (by its block ID)."""
    return sum(BG.record_cost(r) for r in _raw_lines(raw_path) if r.get("block") == block)


def blocks_started(raw_path):
    return {r.get("block") for r in _raw_lines(raw_path)}


def make_writer(raw_path, stoprule, log=print):
    """Thread-safe append of one raw line (fsynced; = v0.45 make_writer), then the stop-rule check."""
    raw_path = Path(raw_path)
    raw_path.parent.mkdir(parents=True, exist_ok=True)
    lock = threading.Lock()

    def write(rec):
        with lock:
            with open(raw_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                f.flush()
                os.fsync(f.fileno())
        log(f"  {rec['call_id']} {rec['status']} out={rec['output_tokens']} fr={rec['finish_reason']} "
            f"${rec['cost_usd']:.4f}")
        if stoprule.check(rec):
            log(f"STOP RULE: {rec.get('model_slot')} paused after {rec['call_id']} (cut at the output limit)")
    return write


def run_collection(specs, ledger, raw_path, runners, stoprule, panel, log=print, write=None):
    """Blocks in order; within a block one worker per model not paused by the stop rule, in parallel.
    Budget pause/stop halts everything; a stop-rule pause halts only its model. After C1, the projection pause
    (section 3.9 iii). Returns 'done' | 'pause' | 'stop' | 'stop_rule'."""
    done = done_ids(raw_path)
    write = write or make_writer(raw_path, stoprule, log)
    started = blocks_started(raw_path)
    for bi, bid in enumerate(BLOCK_IDS):
        todo = [s for s in specs if s["block"] == bid and s["call_id"] not in done]
        groups = []
        for m in panel:
            g = [s for s in todo if s["model"]["slot"] == m["slot"]]
            if g and not stoprule.is_paused(m["slot"]):
                groups.append((g, runners[m["mode"]], ModelLedger(ledger, stoprule, m["slot"])))
        if groups:
            log(f"block {bid}: {sum(len(g) for g, _r, _l in groups)} calls to send; {ledger.summary()}")
            with ThreadPoolExecutor(max_workers=len(groups)) as pool:
                res = list(pool.map(lambda gr: gr[1](gr[0], gr[2], write), groups))
            for st in ("stop", "pause"):
                if st in res:
                    log(f"HALT ({st}) in block {bid}: {ledger.summary()}")
                    return st
        if bid == PROJECTION_BLOCK and not ledger.approved("projection") and not (started & set(BLOCK_IDS[bi + 1:])):
            bc = block_cost(raw_path, bid)
            proj = ledger.spent() + bc * PROJECTION_FACTOR
            if any(BLOCK_IDS.index(s["block"]) > bi and s["call_id"] not in done for s in specs) and proj > ledger.cap:
                ledger.halt("pause", f"projection: spend ${ledger.spent():.2f} + C1 ${bc:.2f} x 489/273 = "
                                     f"${proj:.2f} > ${ledger.cap:.0f}")
                log(f"PAUSE (projection) after {bid}: {ledger.summary()}")
                return "pause"
    return "stop_rule" if stoprule.paused else "done"


