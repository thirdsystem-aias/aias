class Refused(SystemExit):
    """A guard refused (exit code 2); the message says why."""

    def __init__(self, msg):
        super().__init__(2)
        self.msg = msg
        print(f"REFUSED: {msg}", file=sys.stderr)


def probes_sha_expected(path=None):
    """The SHA-256 recorded beside the probe file (and pinned here)."""
    line = Path(PROBES_SHA_PATH if path is None else path).read_text(encoding="utf-8").split()
    return line[0] if line else None


def verify_probes(path=None, sha_path=None):
    """Section 3.5 / MC_Probes: the probe file must hash to the recorded and pinned SHA-256 before anything else."""
    path = Path(PROBES_PATH if path is None else path)
    if not path.exists():
        raise Refused(f"probe file missing: {path}")
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    want = probes_sha_expected(sha_path)
    if got != want or got != PROBES_SHA256:
        raise Refused(f"probe file SHA-256 {got} != recorded {want} / pinned {PROBES_SHA256}")
    return got


def load_probes(path=None):
    path = Path(PROBES_PATH if path is None else path)
    probes = [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
    pred = [p for p in probes if p.get("part") != "choice"]
    cho = [p for p in probes if p.get("part") == "choice"]
    if (len(pred), len(cho)) != (EXPECTED_PREDICTOR_ROWS, EXPECTED_CHOICE_ROWS):
        raise Refused(f"expected {EXPECTED_PREDICTOR_ROWS} predictor + {EXPECTED_CHOICE_ROWS} choice rows, "
                      f"found {len(pred)} + {len(cho)}")
    return probes


