def at_limit(rec):
    """The provider's length stop, or (no finish reason) output (+ Google thinking) tokens at the cap."""
    fr = rec.get("finish_reason")
    if fr:
        return str(fr) in LENGTH_STOPS
    toks = (rec.get("output_tokens") or 0)
    if rec.get("provider") == "google":
        toks += rec.get("thinking_tokens") or 0
    return toks >= CURRENT_MAX_TOKENS


def cut_before_outcome(rec):
    """Choice block: at the limit with no CHOICE: line. Predictor block: at the limit with no complete answer
    text (DECISION: 'complete' = non-empty text; a predictor answer at the limit with text is kept and logged)."""
    if not at_limit(rec):
        return False
    text = rec.get("text") or ""
    if rec.get("part") == "choice":
        return not CHOICE_LINE.search(text)
    return not text.strip()


class StopRule:
    """Trigger: one cut answer from any model -> that model is paused at once; the others go on. Persistent:
    a trigger in STOPRULE_PATH without a later release keeps the model paused on resume."""

    def __init__(self, path=None):
        self.path = Path(STOPRULE_PATH if path is None else path)
        self.lock = threading.Lock()
        self.paused = set()
        if self.path.exists():
            for line in self.path.read_text(encoding="utf-8").splitlines():
                try:
                    ev = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if ev.get("event") == "trigger":
                    self.paused.add(ev["model_slot"])
                elif ev.get("event") == "release":
                    self.paused.discard(ev["model_slot"])

    def check(self, rec):
        if not cut_before_outcome(rec):
            return False
        with self.lock:
            slot = rec.get("model_slot")
            self.paused.add(slot)
            _journal(self.path, {"event": "trigger", "utc": _now(), "model_slot": slot,
                                 "model": rec.get("model_requested"), "call_id": rec.get("call_id"),
                                 "block": rec.get("block"), "finish_reason": rec.get("finish_reason"),
                                 "output_tokens": rec.get("output_tokens"), "thinking_tokens": rec.get("thinking_tokens")})
        return True

    def release(self, slot, note):
        _journal(self.path, {"event": "release", "utc": _now(), "model_slot": slot, "note": note})
        self.paused.discard(slot)

    def is_paused(self, slot):
        with self.lock:
            return slot in self.paused


class ModelLedger:
    """The shared budget Ledger seen by one model's runner: identical, except that no reservation is granted once
    the stop rule has paused this model (so neither runner sends a further request for it)."""

    def __init__(self, ledger, stoprule, slot):
        self._l, self._s, self._slot = ledger, stoprule, slot

    def __getattr__(self, name):
        return getattr(self._l, name)

    def reserve(self, amount):
        if self._s.is_paused(self._slot):
            return "stop_rule", None
        return self._l.reserve(amount)

    def fit(self, per_request, n):
        if self._s.is_paused(self._slot):
            return "stop_rule", 0, None
        return self._l.fit(per_request, n)


