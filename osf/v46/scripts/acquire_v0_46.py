def run(approve_past_80=None, approve_projection=None, log=print):
    """--run: every guard in the documented order, then the collection."""
    global DEADLINE, WINDOW_HARD_END
    verify_probes()
    commit = lock_guard()
    gates_guard()
    panel = panel_guard()
    WINDOW_HARD_END = window_guard()
    other_collection_guard()
    require_keys_v46()
    log(f"guards passed: {PREREG_TAG} -> {commit}; gates green; panel {[m['model_id'] for m in panel]}")
    DEADLINE = collection_deadline(RAW_PATH)
    log(f"collection window: no new request after {DEADLINE.isoformat()}")
    ledger = BG.Ledger(RAW_PATH, STATE_PATH)
    if approve_past_80:
        ledger.approve("past_80", approve_past_80)
    if approve_projection:
        ledger.approve("projection", approve_projection)
    stoprule = StopRule()
    if stoprule.paused:
        log(f"stop rule: still paused (no author decision recorded): {sorted(stoprule.paused)}")
    specs = build_specs(load_probes(), panel)
    write = make_writer(RAW_PATH, stoprule, log)
    n = recover_batches(specs, ledger, write, BATCH_LOG, RAW_PATH)
    if n:
        log(f"recovered {n} batch(es) left in flight by an earlier run; budget {ledger.summary()}")
    log(f"{len(specs)} specs, {len(done_ids())} already done; budget {ledger.summary()}")
    st = run_collection(specs, ledger, RAW_PATH, {"batch": partial(run_anthropic_batch, journal=BATCH_LOG),
                                                  "standard": run_sync}, stoprule, panel, log=log, write=write)
    log(f"result: {st} {ledger.summary()}")
    return {"done": 0, "pause": 5, "stop": 6, "stop_rule": 7}[st]


