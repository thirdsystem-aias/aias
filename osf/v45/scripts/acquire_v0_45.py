def prereg_guard():
    """Refuse unless the prereg tag is on origin and the anchor file names its commit."""
    r = subprocess.run(["git", "ls-remote", "--tags", "origin", PREREG_TAG], cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"REFUSED: git ls-remote failed: {r.stderr.strip()}")
    shas = {}
    for line in r.stdout.splitlines():
        sha, ref = line.split("\t")
        shas[ref] = sha
    tag_ref = f"refs/tags/{PREREG_TAG}"
    if tag_ref not in shas:
        sys.exit(f"REFUSED: tag {PREREG_TAG} not found on origin")
    commit = shas.get(tag_ref + "^{}", shas[tag_ref])  # peeled commit for annotated tags
    if not ANCHOR_PATH.exists():
        sys.exit(f"REFUSED: anchor file missing: {ANCHOR_PATH}")
    text = ANCHOR_PATH.read_text(encoding="utf-8")
    if commit not in text and shas[tag_ref] not in text:
        sys.exit(f"REFUSED: {ANCHOR_PATH.name} does not name the commit of {PREREG_TAG} ({commit})")
    return commit


def done_ids(raw_path=None):
    done = set()
    raw_path = RAW_PATH if raw_path is None else raw_path
    if raw_path.exists():
        for line in raw_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            if (r.get("text") or "").strip() and not r.get("error") and r.get("status", "ok") == "ok":
                done.add(r["call_id"])
    return done


def block_cost(raw_path, block):
    """Actual cost of every raw line of one (phase, condition, run) block."""
    ph, cond, run = block
    tot = 0.0
    if raw_path.exists():
        for line in raw_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                if r.get("phase") == ph and r.get("condition") == cond and r.get("run") == run:
                    tot += BG.record_cost(r)
    return tot


def blocks_started(raw_path):
    """(phase, condition, run) of every block with at least one raw line."""
    out = set()
    if raw_path.exists():
        for line in raw_path.read_text(encoding="utf-8").splitlines():
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            out.add((r.get("phase"), r.get("condition"), r.get("run")))
    return out


def make_writer(raw_path, log=print):
    """Thread-safe append of one raw line (fsynced), with a one-line log."""
    raw_path.parent.mkdir(parents=True, exist_ok=True)
    lock = threading.Lock()

    def write(rec):
        with lock:
            with open(raw_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                f.flush()
                os.fsync(f.fileno())
        s = rec.get("search") or {}
        log(f"  {rec['call_id']} {rec['status']} out={rec['output_tokens']} fr={rec['finish_reason']} "
            f"${rec['cost_usd']:.4f}" + (f" searches={s.get('n_searches')}" if rec["condition"] == "S1" else ""))
    return write


def run_collection(specs, ledger, raw_path, runners, log=print, write=None):
    """Blocks in order; within a block one worker per model in parallel (runners[mode](specs, ledger, write)).
    After the projection block, pause if spend + 2 x that block's cost > cap (unless approved).
    Returns 'done' | 'pause' | 'stop'."""
    done = done_ids(raw_path)
    write = write or make_writer(raw_path, log)
    started = blocks_started(raw_path)    # blocks with any raw line before this invocation sent anything

    for bi, block in enumerate(BLOCKS):
        todo = [s for s in specs if s["block"] == bi and s["call_id"] not in done]
        if todo:
            log(f"block {bi + 1} {block}: {len(todo)} calls to send; {ledger.summary()}")
            groups = [[s for s in todo if s["model"]["model_id"] == m["model_id"]] for m in PANEL]
            groups = [(g, runners[g[0]["model"]["mode"]]) for g in groups if g]
            with ThreadPoolExecutor(max_workers=len(groups)) as pool:
                res = list(pool.map(lambda gr: gr[1](gr[0], ledger, write), groups))
            for st in ("stop", "pause"):
                if st in res:
                    log(f"HALT ({st}) in block {bi + 1}: {ledger.summary()}")
                    return st
        # The projection rule is applied once, when block B-S1 run 1 is complete and no later block has started; a
        # resumed run whose later blocks already have lines passed it (or had it approved) earlier (C26).
        if block == PROJECTION_BLOCK and not ledger.approved("projection") and not (started & set(BLOCKS[bi + 1:])):
            bc = block_cost(raw_path, block)
            proj = ledger.spent() + 2 * bc
            if any(s["block"] > bi and s["call_id"] not in done for s in specs) and proj > ledger.cap:
                ledger.halt("pause", f"projection: spend ${ledger.spent():.2f} + 2 x block cost ${bc:.2f} = ${proj:.2f} > ${ledger.cap:.0f}")
                log(f"PAUSE (projection) after block {bi + 1}: {ledger.summary()}")
                return "pause"
    return "done"


def collect(approve_past_80=None, approve_projection=None):
    global DEADLINE
    other_collection_guard()
    window_open_guard()
    availability_guard()
    commit = prereg_guard()
    print(f"prereg guard passed: {PREREG_TAG} -> {commit}; no other paid collection running")
    require_keys()
    DEADLINE = collection_deadline(RAW_PATH)
    print(f"collection window: no new request after {DEADLINE.isoformat()}")
    ledger = BG.Ledger(RAW_PATH, STATE_PATH)
    if approve_past_80:
        ledger.approve("past_80", approve_past_80)
    if approve_projection:
        ledger.approve("projection", approve_projection)
    specs = build_specs(load_probes())
    write = make_writer(RAW_PATH)
    n = recover_batches(specs, ledger, write, BATCH_LOG, RAW_PATH)
    if n:
        print(f"recovered {n} batch(es) left in flight by an earlier run; budget {ledger.summary()}")
    print(f"{len(specs)} specs, {len(done_ids())} already done; budget {ledger.summary()}")
    st = run_collection(specs, ledger, RAW_PATH, {"batch": partial(run_anthropic_batch, journal=BATCH_LOG),
                                                  "standard": run_sync}, write=write)
    print("result:", st, ledger.summary())
    return {"done": 0, "pause": 5, "stop": 6}[st]


