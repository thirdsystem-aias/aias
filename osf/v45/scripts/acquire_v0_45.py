# ----------------------------------------------------------------- collection guards (C26)
def collection_deadline(raw_path):
    """The earlier of 72 hours after the first recorded call (else now) and WINDOW_HARD_END."""
    first = None
    if Path(raw_path).exists():
        for line in Path(raw_path).read_text(encoding="utf-8").splitlines():
            try:
                t = json.loads(line).get("started_utc")
                t = datetime.fromisoformat(t) if t else None
            except (json.JSONDecodeError, ValueError, TypeError, AttributeError):
                continue
            if t is not None and (first is None or t < first):
                first = t
    start = first or datetime.now(timezone.utc)
    return min(start + timedelta(hours=WINDOW_HOURS), WINDOW_HARD_END)


def past_deadline(ledger=None, now=None):
    if DEADLINE is None or (now or datetime.now(timezone.utc)) <= DEADLINE:
        return False
    if ledger is not None:
        ledger.halt("stop", f"collection window ended at {DEADLINE.isoformat()}")
    return True


def window_open_guard(now=None):
    """Section 4.6: no request before WINDOW_START; none after WINDOW_HARD_END."""
    now = now or datetime.now(timezone.utc)
    if now < WINDOW_START:
        sys.exit(f"REFUSED: the t5 window opens at {WINDOW_START.isoformat()} (now {now.isoformat()})")
    if now > WINDOW_HARD_END:
        sys.exit(f"REFUSED: the t5 window closed at {WINDOW_HARD_END.isoformat()}")
    return True


def availability_guard(path=None):
    """Section 4.3 (MC_Available): refuse unless the availability record (vendor model and deprecation pages read
    the day before the window opens) marks every PANEL model as available."""
    path = Path(AVAILABILITY_PATH if path is None else path)
    if not path.exists():
        sys.exit(f"REFUSED: availability record missing: {path}")
    models = (json.loads(path.read_text(encoding="utf-8")).get("models") or {})
    bad = [m["model_id"] for m in PANEL if not (models.get(m["model_id"]) or {}).get("available")]
    if bad:
        sys.exit("REFUSED: not recorded as available: " + ", ".join(bad) + " (replacement rule, section 4.3)")
    return True


def process_table():
    r = subprocess.run(["ps", "-axo", "pid=,ppid=,command="], capture_output=True, text=True)
    rows = {}
    for line in r.stdout.splitlines():
        parts = line.strip().split(None, 2)
        if len(parts) >= 2 and parts[0].isdigit() and parts[1].isdigit():
            rows[int(parts[0])] = (int(parts[1]), parts[2] if len(parts) == 3 else "")
    return rows


def other_collection_guard(rows=None, me=None):
    """One paid collection on the machine at a time (pre-registration header): refuse while any acquire_v*.py --collect
    runs outside this process's own family (itself, its ancestors, its descendants)."""
    rows = process_table() if rows is None else rows
    me = os.getpid() if me is None else me
    family, p = {me}, me
    while p in rows and rows[p][0] > 0 and rows[p][0] not in family:
        p = rows[p][0]
        family.add(p)
    desc, grew = {me}, True
    while grew:
        grew = False
        for pid, (ppid, _) in rows.items():
            if ppid in desc and pid not in desc:
                desc.add(pid)
                grew = True
    family |= desc
    others = [(pid, cmd) for pid, (ppid, cmd) in rows.items() if pid not in family and PAID_COLLECTION.search(cmd)]
    if others:
        sys.exit("REFUSED: another paid collection is running: " + "; ".join(f"{p} {c[:120]}" for p, c in others))
    return sorted(family)


def _journal(path, event):
    if path is None:
        return
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(event, ensure_ascii=False) + "\n")
        f.flush()
        os.fsync(f.fileno())


def open_batches(path):
    """Batches the journal records as created but not as recorded (a run stopped while they were in flight)."""
    created, recorded = {}, set()
    if path is not None and Path(path).exists():
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            try:
                ev = json.loads(line)
            except json.JSONDecodeError:
                continue
            if ev.get("event") == "created":
                created[ev["batch_id"]] = ev
            elif ev.get("event") == "recorded":
                recorded.add(ev["batch_id"])
    return [ev for bid, ev in created.items() if bid not in recorded]


def written_batch_requests(raw_path):
    """(batch_id, custom_id) of every raw line already written (so a recovered batch never writes a line twice)."""
