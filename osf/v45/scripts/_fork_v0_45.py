def src(name):
    return subprocess.run(["git", "show", f"{SRC_REF}:osf/v42/scripts/{name}"], cwd=ROOT, capture_output=True,
                          text=True, check=True).stdout


def apply(text, reps, label):
    for a, b in reps:
        n = text.count(a)
        if n != 1:
            sys.exit(f"[{label}] replacement source found {n} times (expected 1): {a[:90]!r}")
        text = text.replace(a, b)
    return text


def replace_docstring(text, new):
    i = text.index('"""')
    j = text.index('"""', i + 3) + 3
    return text[:i] + new + text[j:]


